VM_COUNT = 50

# ----------------------------------------------------------------------
# Deterministic competition timeline
# ----------------------------------------------------------------------
#
# Every competition generated by this command uses the same deterministic
# timeline relative to this fixed timestamp.
#
#   competition.created_at
#       |
#       | 1 minute
#       v
#   registration.starts
#       |
#       | 1 minute
#       v
#   registration.ends
#       |
#       | 1 minute
#       v
#   round 1 starts
#       |
#       | 1 minute
#       v
#   round 1 ends
#       |
#       | 1 minute
#       v
#   round 2 starts
#       |
#       ...
#
# A round is exactly one minute.
# The gap between rounds is exactly one minute.
# Registration lasts exactly one minute.
#
# Using a fixed anchor instead of clock.now() means two invocations with
# identical arguments produce identical timestamps.
# ----------------------------------------------------------------------

TIMELINE_EPOCH = clock.now()

REGISTRATION_DURATION = timedelta(minutes=1, seconds=20)
REGISTRATION_TO_ROUND_GAP = timedelta(minutes=1, seconds=20)

# Creation timestamps are deliberately placed before their dependent
# objects. These offsets are deterministic and do not use randomness.
COMPETITION_CREATED_OFFSET = timedelta(minutes=1)
ROUND_CREATED_OFFSET = timedelta(seconds=10)
VM_CREATED_OFFSET = timedelta(seconds=20)

# Upload/artifact timestamps must occur before the round starts.
ARTIFACT_CREATED_OFFSET = timedelta(seconds=20)
UPLOAD_CREATED_OFFSET = timedelta(seconds=10)

# Deployment timestamps must occur after round start and after the plan.
PLAN_CREATED_OFFSET = timedelta(seconds=10)
DEPLOYMENT_CREATED_OFFSET = timedelta(seconds=20)

# Activity is placed deterministically inside the round.
ACTIVITY_START_OFFSET = timedelta(seconds=1)
ACTIVITY_END_OFFSET = timedelta(seconds=59)


class Command(BaseCommand):
    help = "Initialize a deterministic CTF competition with dummy data."

    def add_arguments(self, parser):
        parser.add_argument(
            "--n-teams",
            type=int,
            default=5,
        )
        parser.add_argument(
            "--n-users",
            type=int,
            default=10,
        )
        parser.add_argument(
            "--n-rounds",
            type=int,
            default=10,
        )
        parser.add_argument(
            "--round-duration",
            type=int,
            default=60,
            help="Round duration in seconds. Must be 60.",
        )
        parser.add_argument(
            "--wait-between-rounds",
            type=int,
            default=60,
            help="Time between rounds in seconds. Must be 60.",
        )
        parser.add_argument(
            "--in-round",
            type=int,
            default=None,
            help="1-based round number when state is 'round'.",
        )
        parser.add_argument(
            "--state",
            choices=[
                "registration started",
                "registration ended",
                "round",
                "finished",
            ],
            required=True,
        )
        parser.add_argument(
            "--seed",
            type=int,
            default=1,
        )

    @transaction.atomic
    def handle(self, *args, **options):
        n_teams = options["n_teams"]
        n_users = options["n_users"]
        n_rounds = options["n_rounds"]
        round_duration = options["round_duration"]
        wait_between_rounds = options["wait_between_rounds"]
        in_round = options["in_round"]
        state = options["state"]
        seed = options["seed"]

        print("Validate")

        self._validate(
            n_teams=n_teams,
            n_users=n_users,
            n_rounds=n_rounds,
            round_duration=round_duration,
            wait_between_rounds=wait_between_rounds,
            in_round=in_round,
            state=state,
        )

        round_duration_delta = timedelta(seconds=round_duration)
        wait_between_rounds_delta = timedelta(seconds=wait_between_rounds)

        # One RNG is used exclusively for non-temporal data.
        rng = random.Random(seed)

        print("Clear database")
        self._clear_database()

        # ------------------------------------------------------------------
        # Competition MUST be created before rounds, users, teams, VMs, etc.
        # ------------------------------------------------------------------

        print("Create competition")
        competition = Competition.objects.create(
            name="Cyber Defense Competition",
            created_at=self._competition_created_at(),
            registration_starts_at=self._registration_starts_at(),
            registration_ends_at=self._registration_ends_at(),
        )

        # ------------------------------------------------------------------
        # Rounds
        # ------------------------------------------------------------------

        print("Create rounds")

        rounds = self._create_rounds(
            competition=competition,
            state=state,
            n_rounds=n_rounds,
            in_round=in_round,
            round_duration=round_duration_delta,
            wait_between_rounds=wait_between_rounds_delta,
            rng=rng,
        )

        # ------------------------------------------------------------------
        # Users
        # ------------------------------------------------------------------

        print("Create users")

        users = self._create_users(
            competition=competition,
            n_users=n_users,
            seed=seed,
            rng=rng,
        )

        # ------------------------------------------------------------------
        # Teams
        # ------------------------------------------------------------------

        print("Create teams")

        teams = self._create_teams(
            competition=competition,
            users=users,
            n_teams=n_teams,
            state=state,
            seed=seed,
            rng=rng,
        )

        # ------------------------------------------------------------------
        # Application setting
        # ------------------------------------------------------------------

        print("Create application setting")

        ApplicationSetting.objects.create(
            key="current",
            current_competition=competition,
        )

        # ------------------------------------------------------------------
        # VMs
        # ------------------------------------------------------------------

        print("Create VMs")

        vms_by_round = self._create_vms(
            rounds=rounds,
            seed=seed,
            rng=rng,
        )

        # ------------------------------------------------------------------
        # Gameplay
        # ------------------------------------------------------------------

        if state in {"round", "finished"}:
            activity_rounds = self._get_activity_rounds(
                rounds=rounds,
                state=state,
                in_round=in_round,
            )

            print("Create access tokens")

            access_token_hashes_by_team = self._create_access_tokens(
                teams=teams,
                seed=seed,
                rng=rng,
            )

            print("Create game activity")

            self._create_game_activity(
                teams=teams,
                users=users,
                rounds=activity_rounds,
                vms_by_round=vms_by_round,
                access_token_hashes_by_team=access_token_hashes_by_team,
                seed=seed,
                rng=rng,
            )

        # ------------------------------------------------------------------
        # Final invariant verification.
        # ------------------------------------------------------------------

        print("Assert timestamp invariants")

        self._assert_invariants(
            competition=competition,
            rounds=rounds,
            vms_by_round=vms_by_round,
            state=state,
            in_round=in_round,
            round_duration=round_duration_delta,
            wait_between_rounds=wait_between_rounds_delta,
        )

        print(
            self.style.SUCCESS(
                f"Initialized competition successfully "
                f"(state={state!r}, seed={seed})"
            )
        )

    # ------------------------------------------------------------------
    # Validation
    # ------------------------------------------------------------------

    def _validate(
        self,
        *,
        n_teams,
        n_users,
        n_rounds,
        round_duration,
        wait_between_rounds,
        in_round,
        state,
    ):
        if n_teams < 1:
            raise CommandError("--n-teams must be at least 1.")

        if n_users < 1:
            raise CommandError("--n-users must be at least 1.")

        if n_rounds < 1:
            raise CommandError("--n-rounds must be at least 1.")

        if n_users < n_teams:
            raise CommandError("There must be at least as many users as teams.")

        if n_users > n_teams * 2:
            raise CommandError(
                "There can be at most two users per team, so "
                "--n-users cannot exceed --n-teams * 2."
            )

        if round_duration != 60:
            raise CommandError("--round-duration must be exactly 60 seconds.")

        if wait_between_rounds != 60:
            raise CommandError("--wait-between-rounds must be exactly 60 seconds.")

        if state == "round":
            if in_round is None:
                raise CommandError("--in-round is required when --state='round'.")

            if not 1 <= in_round <= n_rounds:
                raise CommandError(f"--in-round must be between 1 and {n_rounds}.")

        elif in_round is not None:
            raise CommandError("--in-round can only be used with --state='round'.")

