"""From a gameplan's spec to what the node builds (the round agent, scripts/round_agent):

  hcl(spec)              the sandbox stack's generated_vms.tf: bridges, VMs, their firewall rules
  ansible_vars(spec)     what SetupSandbox.yml installs on each VM (role sandbox_vm)
  topology(spec)         the sandbox as a graph, for the run's replay
  seeded_packages(path)  the packages the private apt cache is filled with

Every value written into the HCL was checked by the spec (names, addresses, numbers): the HCL
holds no free text. Ansible gets free text (files, commands), which the agent writes tagged
`!unsafe`, so none of it is ever templated.
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml


def _q(value) -> str:
    """An HCL string literal (the values are restricted to plain characters already)."""
    return json.dumps(str(value))


def hcl(spec: dict, gameplan: str, sha256: str) -> str:
    out = [
        "# Generated by the round agent from a gameplan (src/gameplan/build.py). Runtime state:",
        "# the agent writes it for every round and never reads it back except to compare.",
        "locals {",
        f"  gameplan        = {_q(gameplan)}",
        f"  gameplan_sha256 = {_q(sha256)}",
        "",
        "  sandbox_bridges = {",
    ]
    for net in spec["networks"]:
        out += [f"    {_q(net['name'])} = {{", f"      name         = {_q(net['bridge'])}",
                f"      network_cidr = {_q(net['cidr'])}", "    }"]  # fmt: skip
    out += ["  }", "", "  sandbox_vms = {"]
    for vm in spec["vms"]:
        out += [
            f"    {_q(vm['name'])} = {{",
            f"      cpu                      = {int(vm['cores'])}",
            f"      ram                      = {int(vm['memory'])}",
            f"      disk_size                = {int(vm['disk'])}",
            f"      disk_file_id             = local.platform.os_images[{_q(vm['image'])}].file_id",
            f"      maintenance_network_cidr = {_q(vm['maintenance'])}",
            "      network_devices = [",
            *[f"        {{ bridge = {_q(nic['bridge'])} }}," for nic in vm["nics"]],
            "      ]",
            "      ip_configs = [",
            *[f"        {{ network_cidr = {_q(nic['address'])}, gateway = {_q(nic['gateway']) if nic['gateway'] else 'null'} }},"
              for nic in vm["nics"]],
            "      ]",
            "      firewall_rules = [",
        ]  # fmt: skip
        for rule in vm["firewall"]:
            peers = ",".join(rule["peers"])
            out.append(
                f"        {{ type = {_q(rule['direction'])}, action = {_q(rule['action'])}, proto = {_q(rule['proto'])}, "
                f"dport = {_q(rule['dport']) if rule['dport'] else 'null'}, "
                f"source = {_q(peers) if rule['direction'] == 'in' else 'null'}, "
                f"dest = {_q(peers) if rule['direction'] == 'out' else 'null'} }},"
            )
        out += ["      ]", "    }"]
    out += ["  }", "}", ""]
    return "\n".join(out)


def ansible_vars(spec: dict) -> dict:
    """{sandbox_vm_config: {VM name: what role sandbox_vm does on it}}."""
    return {
        "sandbox_vm_config": {
            vm["name"]: {
                "install": vm["install"],
                "uninstall": vm["uninstall"],
                "files": vm["files"],
                "setup": vm["setup"],
                "services": vm["services"],
                "users": vm["users"],
            }
            for vm in spec["vms"]
        }
    }


def topology(spec: dict) -> dict:
    """The sandbox as nodes and edges (VMs, networks, the gateway), for the replay and the
    staff pages. No firewall rules, files or commands: only what a run's VMs show anyway."""
    nodes = [{"id": "sandbox-gw", "label": "sandbox-gw", "type": "router", "layer": "edge", "site": "sandbox"}]
    edges = []
    for net in spec["networks"]:
        key = f"network:{net['name']}"
        nodes.append({"id": key, "label": net["name"], "type": "network", "layer": "access", "site": "sandbox",
                      "cidr": net["cidr"], "bridge": net["bridge"]})  # fmt: skip
        edges.append({"source": "sandbox-gw", "target": key, "relationship": "gateway"})
    for vm in spec["vms"]:
        key = f"vm:{vm['name']}"
        nodes.append({"id": key, "label": vm["name"], "type": "virtual-machine", "layer": "endpoint", "site": "sandbox",
                      "entrypoint": vm["name"] == spec["entrypoint"]})  # fmt: skip
        for nic in vm["nics"]:
            edges.append({"source": key, "target": f"network:{nic['network']}", "relationship": "attached-to",
                          "address": nic["address"]})  # fmt: skip
    return {"format": "worms-sandbox-topology-1", "nodes": nodes, "edges": edges}


def vm_networks(spec: dict) -> dict:
    """{VM name: [{name, cidr}]}: the networks each VM is on."""
    cidrs = {net["name"]: net["cidr"] for net in spec["networks"]}
    return {vm["name"]: [{"name": nic["network"], "cidr": cidrs[nic["network"]]} for nic in vm["nics"]] for vm in spec["vms"]}


APT_CACHE_DEFAULTS = Path("ansible/roles/private_internet/apt_cache/defaults/main.yml")


def seeded_packages(repo_root) -> list[str] | None:
    """The packages the private apt cache is filled with (apt_cache_seed_packages), or None
    if this checkout does not have the list (the orchestrator does not)."""
    path = Path(repo_root) / APT_CACHE_DEFAULTS
    if not path.is_file():
        return None
    return list(yaml.safe_load(path.read_text()).get("apt_cache_seed_packages") or [])
