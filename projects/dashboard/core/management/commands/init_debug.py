    # Virtual machines
    # ------------------------------------------------------------------

    def _create_vms(
        self,
        *,
        rounds,
        seed,
        rng,
    ):
        services = [
            "web",
            "api",
            "db",
            "mail",
            "vpn",
            "git",
            "dns",
        ]

        vms_by_round = {}

        for round_index, round_obj in enumerate(
            rounds,
            start=1,
        ):
            vms = []

            used_identifiers = set()

            created_at = self._vm_created_at(
                round_index,
            )

            if not created_at < round_obj.round_start:
                raise CommandError(
                    f"VMs for round {round_index} must be created "
                    f"before the round starts."
                )

            for vm_index in range(VM_COUNT):
                service = rng.choice(services)

                identifier = f"r{round_index}-" f"{service}-" f"{vm_index + 1}"

                while identifier in used_identifiers:
                    service = rng.choice(services)

                    identifier = f"r{round_index}-" f"{service}-" f"{vm_index + 1}"

                used_identifiers.add(identifier)

                third_octet = 10 + ((round_index * 7 + vm_index) % 200)

                # IP assignment is non-temporal randomness.
                fourth_octet = rng.randint(2, 254)

                vm = VirtualMachine.objects.create(
                    vm_identifier=identifier,
                    vm_maintenance_ip=(
                        f"10.{round_index}." f"{third_octet}." f"{fourth_octet}"
                    ),
                    ctf_flag_hash=self._hash(
                        seed,
                        "ctf-flag",
                        round_index,
                        vm_index,
                    ),
                    round=round_obj,
                    created_at=created_at,
                )

                vms.append(vm)

            vms_by_round[round_obj.pk] = vms

        return vms_by_round

    # ------------------------------------------------------------------
    # Access tokens
    # ------------------------------------------------------------------

    def _create_access_tokens(
        self,
        *,
        teams,
        seed,
        rng,
    ):
        active_token_hashes_by_team = {}

        for team_index, team in enumerate(teams):
            # Token count is assignment-like data, not temporal data.
            token_count = rng.choices(
                [1, 2, 3],
                weights=[70, 25, 5],
                k=1,
            )[0]

            members = list(
                TeamMembership.objects.filter(team=team).prefetch_related("user")
            )

            if not members:
                raise CommandError(f"Team {team.pk} has no members.")

            active_hashes = []

            for token_index in range(token_count):
                revoked = token_index != 0 and rng.random() < 0.08

                access_token_hash = self._token_hash(
                    seed,
                    "access",
                    team_index,
                    token_index,
                )

                AccessTokens.objects.create(
                    name=f"token-{token_index + 1}",
                    description=(
                        "Competition access token"
                        if not revoked
                        else "Revoked competition access token"
                    ),
                    access_token_hash=access_token_hash,
                    team=team,
                    created_by=rng.choice(members).user,
                    revoked=revoked,
                    revoked_at=(
                        # Access-token revocation is not part of the
                        # competition event timeline. Use a deterministic
                        # fixed timestamp.
                        self._registration_ends_at()
                        if revoked
                        else None
                    ),
                )

                if not revoked:
                    active_hashes.append(access_token_hash)

            active_token_hashes_by_team[team.pk] = active_hashes

        return active_token_hashes_by_team

    # ------------------------------------------------------------------
    # Gameplay
    # ------------------------------------------------------------------

    def _get_activity_rounds(
        self,
        *,
        rounds,
        state,
        in_round,
    ):
        if state == "round":
            return rounds[:in_round]

        if state == "finished":
            return rounds

        return []

    def _create_game_activity(
        self,
        *,
        teams,
        users,
        rounds,
        vms_by_round,
        access_token_hashes_by_team,
        seed,
        rng,
    ):
        deployed_on_vms: Set[int] = set()

        for team in teams:
            members = list(team.users.all())

            if not members:
                continue

            access_token_hashes = access_token_hashes_by_team.get(
                team.pk,
                [],
            )

            if not access_token_hashes:
                continue

            deployments_by_round = self._create_team_uploads(
                team=team,
                members=members,
                rounds=rounds,
                vms_by_round=vms_by_round,
                seed=seed,
                rng=rng,
                deployed_on_vms=deployed_on_vms,
            )

            for round_obj in rounds:
                vms = vms_by_round.get(
                    round_obj.pk,
                    [],
                )

                if not vms:
                    continue

                deployment = deployments_by_round.get(
                    round_obj.pk,
                )

                # No deployment means no gameplay activity.
                if deployment is None:
                    continue

                self._create_logs_for_team_round(
                    team=team,
                    round_obj=round_obj,
                    access_token_hashes=access_token_hashes,
                    seed=seed,
                    rng=rng,
                )

                self._create_captures_for_team_round(
                    team=team,
                    round_obj=round_obj,
                    vms=vms,
                    access_token_hashes=access_token_hashes,
                    seed=seed,
                    rng=rng,
                )

    # ------------------------------------------------------------------
    # Uploads / worm deployments
    # ------------------------------------------------------------------

    def _create_team_uploads(
        self,
        *,
        team: Team,
        members,
        rounds: List[Round],
        vms_by_round: Dict[int, List[VirtualMachine]],
        seed,
        rng: random.Random,
        deployed_on_vms: Set[int],
    ):
        """
        Generate worm uploads and deployments.

        Required ordering:

            MalwareArtifact.created_at
                <
            Upload.created_at
                <
            Round.round_start
                <
            WormDeploymentPlan.created_at
                <
            WormDeployment.created_at
        """

        deployments_by_round: Dict[int, WormDeployment] = {}

        if not rounds:
            return deployments_by_round

        # Number of uploads is deliberately based on deterministic
        # team position rather than temporal randomness.
        #
        # Randomness is used for selecting which artifacts are deployed
        # and where they are deployed.
        upload_count = 1 + (team.pk % 3)

        for upload_index in range(upload_count):
            # Assign an artifact to a deterministic round. The actual
            # deployment round can still be selected randomly.
            artifact_round_number = 1

            content_hash = self._hash(
                seed,
                "artifact",
                team.pk,
                upload_index,
            )

            artifact_created_at = self._artifact_created_at(
                artifact_round_number,
                round_duration=timedelta(minutes=1),
                wait_between_rounds=timedelta(minutes=1),
            )

            artifact = MalwareArtifact.objects.create(
                content_hash=content_hash,
                storage_key=(f"malware/" f"{content_hash[:2]}/" f"{content_hash}"),
                created_at=artifact_created_at,
            )

            user = rng.choice(members)

            candidate_rounds = [
                round_obj
                for round_obj in rounds
                if round_obj.pk not in deployments_by_round
            ]

            # Keep some uploads as unused artifacts.
            should_deploy = bool(candidate_rounds) and rng.random() < 0.75

            if not should_deploy:
                upload_created_at = self._upload_created_at(
                    artifact_round_number,
                    round_duration=timedelta(minutes=1),
                    wait_between_rounds=timedelta(minutes=1),
                )

                Upload.objects.create(
                    artifact=artifact,
                    user=user,
                    created_at=upload_created_at,
                )

                continue

            round_obj = rng.choice(candidate_rounds)

            round_number = rounds.index(round_obj) + 1

            vms = vms_by_round.get(
                round_obj.pk,
                [],
            )

            if not vms:
                upload_created_at = self._upload_created_at(
                    artifact_round_number,
                    round_duration=timedelta(minutes=1),
                    wait_between_rounds=timedelta(minutes=1),
                )

                Upload.objects.create(
                    artifact=artifact,
                    user=user,
                    created_at=upload_created_at,
                )

                continue

            upload_created_at = self._upload_created_at(
                artifact_round_number,
                round_duration=timedelta(minutes=1),
                wait_between_rounds=timedelta(minutes=1),
            )

            upload = Upload.objects.create(
                artifact=artifact,
                user=user,
                created_at=upload_created_at,
            )

            available_vms = [vm for vm in vms if vm.pk not in deployed_on_vms]

            if not available_vms:
                continue

            vm = rng.choice(available_vms)

            plan_created_at = self._plan_created_at(
                round_number,
                round_duration=timedelta(minutes=1),
                wait_between_rounds=timedelta(minutes=1),
            )

            deployment_created_at = self._deployment_created_at(
                round_number,
                round_duration=timedelta(minutes=1),
                wait_between_rounds=timedelta(minutes=1),
            )

            if not (
                artifact.created_at
                < upload.created_at
                < round_obj.round_start
                < plan_created_at
                < deployment_created_at
                < round_obj.round_end
            ):
                raise CommandError(
                    f"Invalid worm deployment timeline for " f"round {round_number}."
                )

            worm_deployment_plan = WormDeploymentPlan.objects.create(
                team=team,
                upload=upload,
                virtual_machine=vm,
                round=vm.round,
                created_at=plan_created_at,
            )

            deployment = WormDeployment.objects.create(
                worm_deployment_plan=worm_deployment_plan,
                created_at=deployment_created_at,
            )

            deployments_by_round[round_obj.pk] = deployment
            deployed_on_vms.add(vm.pk)

        return deployments_by_round

    # ------------------------------------------------------------------
    # Logging
    # ------------------------------------------------------------------

    def _create_logs_for_team_round(
        self,
        *,
        team,
        round_obj,
        access_token_hashes,
        seed,
        rng: random.Random,
    ):
        """
        LoggingAttempt and Logging timestamps are deterministic and
        constrained to the round.
        """

        events = [
            "ssh_login",
            "http_request",
            "dns_query",
            "process_start",
            "connection",
        ]

        # Number of log events is deterministic. RNG is only used for
        # event/token/value distribution.
        count = 3 + (team.pk % 4)

        for index in range(count):
            created_at = self._activity_timestamp(
                round_number=(
                    int(round_obj.name.removeprefix("Round ").strip())
                    if round_obj.name.startswith("Round ")
                    else round_obj.pk
                ),
                index=index,
                total=count,
                round_duration=timedelta(minutes=1),
                wait_between_rounds=timedelta(minutes=1),
            )

            log_data = {
                "event": rng.choice(events),
                "success": rng.random() < 0.70,
            }

            attempt = LoggingAttempt.objects.create(
                uuid=self._uuid(
                    seed,
                    "logging-attempt",
                    team.pk,
                    round_obj.pk,
                    index,
                ),
                team_uuid=str(team.uuid),
                log_data=log_data,
                processed=True,
                processed_at=created_at,
                created_at=created_at,
            )

            Logging.objects.create(
                team=team,
                round=round_obj,
                logging_attempt=attempt,
                created_at=created_at,
            )

    # ------------------------------------------------------------------
    # Flag captures
    # ------------------------------------------------------------------

    def _create_captures_for_team_round(
        self,
        *,
        team,
        round_obj,
        vms: List[VirtualMachine],
        access_token_hashes,
        seed,
        rng: random.Random,
    ):
        """
        FlagCaptureAttempt and FlagCapture timestamps are deterministic
        and constrained to the round.

        Randomness is used only for scoring distribution:
        VM selection, token selection, and success/failure.
        """

        # Deterministic number of attempts.
        count = min(
            VM_COUNT,
            5 + (team.pk % 16),
        )

        round_number = (
            int(round_obj.name.removeprefix("Round ").strip())
            if round_obj.name.startswith("Round ")
            else round_obj.pk
        )

        for index in range(count):
            vm = rng.choice(vms)

            created_at = self._activity_timestamp(
                round_number=round_number,
                index=index,
                total=count,
                round_duration=timedelta(minutes=1),
                wait_between_rounds=timedelta(minutes=1),
            )

            attempt = FlagCaptureAttempt.objects.create(
                team_uuid=str(team.uuid),
                vm_flag_hash=vm.ctf_flag_hash,
                processed=True,
                processed_at=created_at,
                created_at=created_at,
            )

            # Randomness affects point/scoring distribution only.
            success_probability = 0.55

            if rng.random() >= success_probability:
                continue

            FlagCapture.objects.create(
                team=team,
                round=round_obj,
                vm=vm,
                flag_capture_attempt=attempt,
                created_at=created_at,
            )

    # ------------------------------------------------------------------
    # Assertions
    # ------------------------------------------------------------------

    def _assert_invariants(
        self,
        *,
        competition: Competition,
        rounds: List[Round],
        vms_by_round: Dict[int, VirtualMachine],
        state,
        in_round,
        round_duration,
        wait_between_rounds,
    ):
        """
        Explicitly verify every temporal invariant required by the
        generated data.

        These assertions intentionally execute after all objects have
        been created so a violation cannot silently pass.
        """

        # --------------------------------------------------------------
        # 1. Competition exists before rounds.
        # --------------------------------------------------------------

        if not rounds:
            raise CommandError("At least one round must exist.")

        # --------------------------------------------------------------
        # 2. Competition registration ordering.
        # --------------------------------------------------------------

        if not (
            competition.created_at
            < competition.registration_starts_at
            < competition.registration_ends_at
            < rounds[0].round_start
        ):
            raise CommandError("Competition registration timestamp invariant failed.")

        # --------------------------------------------------------------
        # 3. Round start < round end.
        # --------------------------------------------------------------

        for index, round_obj in enumerate(
            rounds,
            start=1,
        ):
            if not (round_obj.round_start < round_obj.round_end):
                raise CommandError(
                    f"Round {index} violates " "round_start < round_end."
                )

        # --------------------------------------------------------------
        # 4. Competition created_at < round.created_at.
        # --------------------------------------------------------------

        for index, round_obj in enumerate(
            rounds,
            start=1,
        ):
            if not (competition.created_at < round_obj.created_at):
                raise CommandError(
                    f"Round {index} violates "
                    "competition.created_at < round.created_at."
                )

        # --------------------------------------------------------------
        # 5. Logging/scoring attempts are inside their round.
        # --------------------------------------------------------------

        for round_obj in rounds:
            logging_attempts = LoggingAttempt.objects.filter(
                logging__round=round_obj,
            ).distinct()

            for attempt in logging_attempts:
                if not (
                    round_obj.round_start <= attempt.created_at <= round_obj.round_end
                ):
                    raise CommandError(
                        f"LoggingAttempt {attempt.pk} is outside " f"{round_obj.name}."
                    )

            capture_attempts = FlagCaptureAttempt.objects.filter(
                flag_captures__round=round_obj,
            ).distinct()

            for attempt in capture_attempts:
                if not (
                    round_obj.round_start <= attempt.created_at <= round_obj.round_end
                ):
                    raise CommandError(
                        f"FlagCaptureAttempt {attempt.pk} is outside "
                        f"{round_obj.name}."
                    )

        # --------------------------------------------------------------
        # 6. VMs are created before their round starts.
        # --------------------------------------------------------------

        for round_obj in rounds:
            vms = vms_by_round.get(
                round_obj.pk,
                [],
            )

            for vm in vms:
                if not (vm.created_at < round_obj.round_start):
                    raise CommandError(
                        f"VirtualMachine {vm.pk} for {round_obj.name} "
                        "was not created before the round."
                    )

        # --------------------------------------------------------------
        # 7. Worm deployment dependency ordering.
        # --------------------------------------------------------------

        deployments = WormDeployment.objects.select_related(
            "worm_deployment_plan",
            "worm_deployment_plan__upload",
            "worm_deployment_plan__upload__artifact",
            "worm_deployment_plan__round",
        ).all()

        for deployment in deployments:
            plan = deployment.worm_deployment_plan
            upload = plan.upload
            artifact = upload.artifact
            round_obj = plan.round

            if not (
                artifact.created_at
                < upload.created_at
                < round_obj.round_start
                < plan.created_at
                < deployment.created_at
            ):
                raise CommandError(
                    f"WormDeployment {deployment.pk} violates "
                    "artifact < upload < round_start < plan < deployment."
                )

        # --------------------------------------------------------------
        # Additional strict checks.
        # --------------------------------------------------------------

        for index, round_obj in enumerate(
            rounds,
            start=1,
        ):
            expected_start = self._round_start(
                index,
                round_duration=round_duration,
                wait_between_rounds=wait_between_rounds,
            )
            expected_end = self._round_end(
                index,
                round_duration=round_duration,
                wait_between_rounds=wait_between_rounds,
            )

            if round_obj.round_start != expected_start:
                raise CommandError(
                    f"{round_obj.name} does not use the deterministic "
                    "round start timestamp."
                )

            if round_obj.round_end != expected_end:
                raise CommandError(
                    f"{round_obj.name} does not use the deterministic "
                    "round end timestamp."
                )

        # Registration is exactly one minute.
        if (
            competition.registration_ends_at - competition.registration_starts_at
            != REGISTRATION_DURATION
        ):
            raise CommandError("Registration period must be exactly one minute.")

        # Every round has the duration supplied through the CLI.
        for round_obj in rounds:
            if round_obj.round_end - round_obj.round_start != round_duration:
                raise CommandError(
                    f"{round_obj.name} must be exactly "
                    f"{round_duration.total_seconds()} seconds long."
                )

        # Adjacent rounds have the gap supplied through the CLI.
        for previous, current in zip(
            rounds,
            rounds[1:],
        ):
            gap = current.round_start - previous.round_end

            if gap != wait_between_rounds:
                raise CommandError(
                    f"Invalid gap between " f"{previous.name} and {current.name}."
                )

        print(self.style.SUCCESS("All timestamp invariants passed."))
