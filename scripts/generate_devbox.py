#!/usr/bin/env python3
"""Generate the devbox OpenTofu definition (opentofu/stacks/devbox/
generated_devboxes.tf) for a set of teams.

The devbox stack holds EVERY team's devbox at once, so this generator takes the
full team list and emits one block covering all of them (the round agent runs
it on devbox_provision/devbox_rebuild and `tofu apply`s the stack). Addressing
is derived deterministically from each team's integer index, inside the devbox
ranges in opentofu/shared/shared-variables.tf:

    devbox networks   10.128.0.0/10   team i -> 10.128.(2i).0/24 (A-B link),
                                               10.128.(2i+1).0/24 (B-C link)
    devbox SSH fabric 10.7.0.0/16      team i -> 10.7.i.{11,12,13} (A,B,C)
    devbox maint.     10.6.0.0/16      team i -> 10.6.i.{1,11,12,13} (gw,A,B,C)
    services block    10.2.0.32/27     team i -> 10.2.0.(32+i)  (devbox-gw SNAT)

So team 0..31 are supported (the services block holds 32). Each team gets two
bridges, a devbox-gw and three VMs A/B/C wired A-B and B-C (B is the pivot).

Input: a JSON array of teams on stdin or --teams-file, each
{"slug": "t1", "index": 0}. Output: the HCL on stdout (or --output).
"""

from __future__ import annotations

import argparse
import ipaddress
import json
import re
import sys

DEVBOX_NETWORK = ipaddress.ip_network("10.128.0.0/10")
SERVICES_BLOCK = ipaddress.ip_network("10.2.0.32/27")
SSH_FABRIC_PREFIX = 16
MAINT_PREFIX = 16

SLUG_RE = re.compile(r"^[a-z0-9]([a-z0-9-]{0,30}[a-z0-9])?$")


def team_addressing(slug: str, index: int) -> dict:
    """Deterministic addressing for a team's devbox from its index."""
    if index < 0 or index >= SERVICES_BLOCK.num_addresses:
        raise ValueError(f"team index {index} out of range (0..{SERVICES_BLOCK.num_addresses - 1})")
    ab = ipaddress.ip_network(f"10.128.{2 * index}.0/24")
    bc = ipaddress.ip_network(f"10.128.{2 * index + 1}.0/24")
    if not (ab.subnet_of(DEVBOX_NETWORK) and bc.subnet_of(DEVBOX_NETWORK)):
        raise ValueError(f"team {slug}: networks outside the devbox range")
    services_ip = str(list(SERVICES_BLOCK.hosts())[index])
    return {
        "slug": slug,
        "ab_name": f"vmbr9{2 * index:03d}",
        "bc_name": f"vmbr9{2 * index + 1:03d}",
        "ab_cidr": str(ab),
        "bc_cidr": str(bc),
        "gw_ab": f"10.128.{2 * index}.1/24",
        "gw_bc": f"10.128.{2 * index + 1}.1/24",
        "gw_ab_ip": f"10.128.{2 * index}.1",
        "gw_bc_ip": f"10.128.{2 * index + 1}.1",
        "services_cidr": f"{services_ip}/24",
        "a_cidr": f"10.128.{2 * index}.11/24",
        "b_ab_cidr": f"10.128.{2 * index}.12/24",
        "b_bc_cidr": f"10.128.{2 * index + 1}.12/24",
        "c_cidr": f"10.128.{2 * index + 1}.13/24",
        "ssh_a": f"10.7.{index}.11/{SSH_FABRIC_PREFIX}",
        "ssh_b": f"10.7.{index}.12/{SSH_FABRIC_PREFIX}",
        "ssh_c": f"10.7.{index}.13/{SSH_FABRIC_PREFIX}",
        "maint_gw": f"10.6.{index}.1/{MAINT_PREFIX}",
        "maint_a": f"10.6.{index}.11/{MAINT_PREFIX}",
        "maint_b": f"10.6.{index}.12/{MAINT_PREFIX}",
        "maint_c": f"10.6.{index}.13/{MAINT_PREFIX}",
    }


def render(teams: list[dict]) -> str:
    addrs = []
    seen = set()
    for team in teams:
        slug = team["slug"]
        if not SLUG_RE.match(slug):
            raise ValueError(f"invalid team slug: {slug!r}")
        if slug in seen:
            raise ValueError(f"duplicate team slug: {slug!r}")
        seen.add(slug)
        addrs.append(team_addressing(slug, int(team["index"])))

    bridges, gws, vms = [], [], []
    for a in addrs:
        s = a["slug"]
        bridges.append(f'    "{s}-ab" = {{ name = "{a["ab_name"]}", team = "{s}", network_cidr = "{a["ab_cidr"]}" }}')
        bridges.append(f'    "{s}-bc" = {{ name = "{a["bc_name"]}", team = "{s}", network_cidr = "{a["bc_cidr"]}" }}')
        gws.append(
            f'    "{s}" = {{\n'
            f'      name             = "devbox-{s}-gw"\n'
            f'      team             = "{s}"\n'
            f'      segments         = ["{s}-ab", "{s}-bc"]\n'
            f'      segment_cidrs    = {{ "{s}-ab" = "{a["gw_ab"]}", "{s}-bc" = "{a["gw_bc"]}" }}\n'
            f'      services_cidr    = "{a["services_cidr"]}"\n'
            f'      maintenance_cidr = "{a["maint_gw"]}"\n'
            f"    }}"
        )
        vms.append(_vm(f"devbox-{s}-a", s, [f"{s}-ab"], {f"{s}-ab": a["a_cidr"]}, a["gw_ab_ip"], a["ssh_a"], a["maint_a"]))
        vms.append(_vm(f"devbox-{s}-b", s, [f"{s}-ab", f"{s}-bc"], {f"{s}-ab": a["b_ab_cidr"], f"{s}-bc": a["b_bc_cidr"]}, a["gw_ab_ip"], a["ssh_b"], a["maint_b"]))
        vms.append(_vm(f"devbox-{s}-c", s, [f"{s}-bc"], {f"{s}-bc": a["c_cidr"]}, a["gw_bc_ip"], a["ssh_c"], a["maint_c"]))

    nl = "\n"
    return (
        "# GENERATED by scripts/generate_devbox.py. Do not edit by hand.\n"
        "# One devbox per team (docs/devbox.md): two bridges (A-B, B-C), a\n"
        "# devbox-gw and three VMs A/B/C. Addresses are derived from the team index.\n\n"
        "locals {\n"
        "  devbox_bridges = {\n" + nl.join(bridges) + "\n  }\n\n"
        "  devbox_gws = {\n" + nl.join(gws) + "\n  }\n\n"
        "  devbox_vms = {\n" + nl.join(vms) + "\n  }\n"
        "}\n"
    )


def _vm(name, team, segments, segment_cidrs, gateway_ip, ssh_cidr, maint_cidr) -> str:
    seg_list = ", ".join(f'"{s}"' for s in segments)
    seg_map = ", ".join(f'"{k}" = "{v}"' for k, v in segment_cidrs.items())
    return (
        f'    "{name}" = {{\n'
        f'      name             = "{name}"\n'
        f'      team             = "{team}"\n'
        f"      segments         = [{seg_list}]\n"
        f"      segment_cidrs    = {{ {seg_map} }}\n"
        f'      gateway_ip       = "{gateway_ip}"\n'
        f'      ssh_fabric_cidr  = "{ssh_cidr}"\n'
        f'      maintenance_cidr = "{maint_cidr}"\n'
        f"    }}"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--teams-file", help="JSON file of [{slug, index}]; default stdin")
    parser.add_argument("--output", help="write here instead of stdout")
    args = parser.parse_args()

    raw = open(args.teams_file).read() if args.teams_file else sys.stdin.read()
    teams = json.loads(raw or "[]")
    hcl = render(teams)
    if args.output:
        open(args.output, "w").write(hcl)
    else:
        sys.stdout.write(hcl)


if __name__ == "__main__":
    main()
