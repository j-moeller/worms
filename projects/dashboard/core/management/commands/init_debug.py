    # ------------------------------------------------------------------
    # Deterministic helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _hash(seed, *parts):
        value = ":".join(
            [
                str(seed),
                *(str(part) for part in parts),
            ]
        )

        return hashlib.sha256(value.encode("utf-8")).hexdigest()

    @classmethod
    def _uuid(cls, seed, *parts):
        return uuid.uuid5(
            uuid.NAMESPACE_URL,
            cls._hash(seed, *parts),
        )

    @classmethod
    def _token_hash(cls, seed, *parts):
        return cls._hash(
            seed,
            "token",
            *parts,
        )

    # ------------------------------------------------------------------
    # Deterministic timeline
    # ------------------------------------------------------------------

    @staticmethod
    def _competition_created_at():
        return TIMELINE_EPOCH + COMPETITION_CREATED_OFFSET

    @staticmethod
    def _registration_starts_at():
        return TIMELINE_EPOCH + COMPETITION_CREATED_OFFSET + timedelta(minutes=1)

    @staticmethod
    def _registration_ends_at():
        return Command._registration_starts_at() + REGISTRATION_DURATION

    @staticmethod
    def _first_round_start():
        return Command._registration_ends_at() + REGISTRATION_TO_ROUND_GAP

    @staticmethod
    def _round_start(
        round_number,
        *,
        round_duration,
        wait_between_rounds,
    ):
        """
        round_number is 1-based.

        Round starts are:

            round 1 = 00:03
            round 2 = 00:05
            round 3 = 00:07
            ...

        because every round is one minute and the gap is one minute.
        """
        if round_number < 1:
            raise ValueError("round_number must be >= 1")

        return Command._first_round_start() + (round_number - 1) * (
            round_duration + wait_between_rounds
        )

    @staticmethod
    def _round_end(
        round_number,
        *,
        round_duration,
        wait_between_rounds,
    ):
        return (
            Command._round_start(
                round_number,
                round_duration=round_duration,
                wait_between_rounds=wait_between_rounds,
            )
            + round_duration
        )

    @staticmethod
    def _round_created_at(round_number):
        """
        Round creation happens ten seconds after competition creation,
        independently of when the round itself starts.

        This guarantees:

            competition.created_at < round.created_at
            round.created_at < round.round_start
        """
        return (
            Command._competition_created_at()
            + ROUND_CREATED_OFFSET
            + timedelta(seconds=round_number)
        )

    @staticmethod
    def _vm_created_at(round_number):
        """
        VM creation occurs before the corresponding round.

        For every round:

            competition.created_at
                <
            vm.created_at
                <
            round.round_start
        """
        return (
            Command._competition_created_at()
            + VM_CREATED_OFFSET
            + timedelta(seconds=round_number)
        )

    @staticmethod
    def _artifact_created_at(
        round_number,
        *,
        round_duration,
        wait_between_rounds,
    ):
        """
        Malware artifacts are created before the upload and before the
        round starts.
        """
        return (
            Command._round_start(
                round_number,
                round_duration=round_duration,
                wait_between_rounds=wait_between_rounds,
            )
            - ARTIFACT_CREATED_OFFSET
        )

    @staticmethod
    def _upload_created_at(
        round_number,
        *,
        round_duration,
        wait_between_rounds,
    ):
        """
        Uploads are created after the artifact and before the round.
        """
        return (
            Command._round_start(
                round_number,
                round_duration=round_duration,
                wait_between_rounds=wait_between_rounds,
            )
            - UPLOAD_CREATED_OFFSET
        )

    @staticmethod
    def _plan_created_at(
        round_number,
        *,
        round_duration,
        wait_between_rounds,
    ):
        return (
            Command._round_start(
                round_number,
                round_duration=round_duration,
                wait_between_rounds=wait_between_rounds,
            )
            + PLAN_CREATED_OFFSET
        )

    @staticmethod
    def _deployment_created_at(
        round_number,
        *,
        round_duration,
        wait_between_rounds,
    ):
        return (
            Command._round_start(
                round_number,
                round_duration=round_duration,
                wait_between_rounds=wait_between_rounds,
            )
            + DEPLOYMENT_CREATED_OFFSET
        )

    @staticmethod
    def _activity_timestamp(
        *,
        round_number,
        index,
        total,
        round_duration,
        wait_between_rounds,
    ):
        """
        Produce a deterministic timestamp inside a round.

        There is deliberately no RNG here.

        For one event, it occurs one second into the round.

        For multiple events, they are evenly distributed between
        second 1 and second 59.
        """
        round_start = Command._round_start(
            round_number,
            round_duration=round_duration,
            wait_between_rounds=wait_between_rounds,
        )

        if total <= 1:
            offset_seconds = 1
        else:
            usable_seconds = 58
            offset_seconds = 1 + (index * usable_seconds) // (total - 1)

        return round_start + timedelta(seconds=offset_seconds)

    # ------------------------------------------------------------------
    # Rounds
    # ------------------------------------------------------------------

    def _create_rounds(
        self,
        *,
        competition,
        state,
        n_rounds,
        in_round,
        round_duration,
        wait_between_rounds,
        rng,
    ):
        """
        Create all rounds using deterministic timestamps.

        State does not affect timestamps.

        All rounds are created because the competition definition contains
        the complete schedule. Activity generation is what is truncated
        for --state=round --in-round=N.
        """

        rounds = []

        for index in range(n_rounds):
            round_number = index + 1

            round_start = self._round_start(
                round_number,
                round_duration=round_duration,
                wait_between_rounds=wait_between_rounds,
            )
            round_end = self._round_end(
                round_number,
                round_duration=round_duration,
                wait_between_rounds=wait_between_rounds,
            )
            created_at = self._round_created_at(round_number)

            if not competition.created_at < created_at:
                raise CommandError(
                    f"Invalid creation timestamp for round {round_number}."
                )

            if not created_at < round_start:
                raise CommandError(
                    f"Round {round_number} must be created before it starts."
                )

            if not round_start < round_end:
                raise CommandError(f"Round {round_number} must end after it starts.")

            round_obj = Round.objects.create(
                seed=rng.randint(
                    0,
                    2**63 - 1,
                ),
                round_start=round_start,
                round_end=round_end,
                name=f"Round {round_number}",
                competition=competition,
                created_at=created_at,
            )

            print(
                f"Generated round ({round_obj.name}): " f"{round_start} -> {round_end}"
            )

            rounds.append(round_obj)

        return rounds

