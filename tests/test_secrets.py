"""The vault (src/worms_cli/secrets.py): the one place secrets are kept.

The Proxmox tokens are entered once (`worms secrets set`); everything else is
generated when missing and never rotated; values are never printed. Runs
without ansible-vault (plaintext vault in a temporary checkout) and, where it
is installed, with it (encrypted at rest).
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys

import pytest
import yaml

from conftest import REPO

sys.path.insert(0, str(REPO / "src"))

from worms_cli import secrets  # noqa: E402
from worms_cli.secrets import EXTERNAL, GENERATED, SSH_KEY, SSH_PUBLIC_KEY, Vault, VaultError  # noqa: E402

MANAGE = REPO / "src" / "manage.py"
needs_ssh_keygen = pytest.mark.skipif(not shutil.which("ssh-keygen"), reason="not installed: ssh-keygen")


@pytest.fixture
def plain(monkeypatch):
    """No ansible-vault: the vault stays readable."""
    real = shutil.which
    monkeypatch.setattr(secrets.shutil, "which", lambda name: None if name == "ansible-vault" else real(name))


@needs_ssh_keygen
def test_ensure_generates_everything_once(tmp_path, plain):
    vault = Vault(tmp_path)
    added = vault.ensure()
    values = vault.load()
    assert set(GENERATED) | {SSH_KEY} <= set(added)
    assert all(len(values[key]) >= 24 for key in GENERATED)
    assert values[SSH_KEY].startswith("-----BEGIN OPENSSH PRIVATE KEY-----")
    assert values[SSH_PUBLIC_KEY].startswith("ssh-ed25519 ")
    # Entered secrets are there (empty) for Ansible from the start.
    assert all(values[key] == "" for key, _, _ in EXTERNAL.values())
    assert oct(vault.file.stat().st_mode & 0o777) == "0o600"
    assert oct(vault.key_file.stat().st_mode & 0o777) == "0o600"
    before = vault.file.read_text()
    assert vault.ensure() == [] and vault.file.read_text() == before  # never rotated


@needs_ssh_keygen
def test_an_older_vault_is_completed_not_rotated(tmp_path, plain):
    """A vault written by the former generate_secrets.py (plain quoted lines,
    comments, keys of removed features) gains the new keys only."""
    old = tmp_path / "ansible" / "group_vars" / "vault.yml"
    old.parent.mkdir(parents=True)
    old.write_text('# GENERATED by scripts/generate_secrets.py\n\nvault_postgres_admin_password: "old-admin-pw"\n'
                   'vault_django_admin_password: "kept"\nvault_tofu_proxmox_api_token: "root@pam!worms=s3cret"\n')
    vault = Vault(tmp_path)
    vault.ensure()
    values = vault.load()
    assert values["vault_postgres_admin_password"] == "old-admin-pw"
    assert values["vault_django_admin_password"] == "kept"  # unknown keys are kept as they are
    assert values["vault_tofu_proxmox_api_token"] == "root@pam!worms=s3cret"
    assert values["vault_orchestrator_secret_key"]


@needs_ssh_keygen
def test_ansible_reads_what_the_vault_writes(tmp_path, plain):
    """JSON-quoted values are YAML: Ansible gets the same strings, the SSH key
    with its newlines."""
    vault = Vault(tmp_path)
    vault.ensure()
    vault.set("proxmox-token", "root@pam!worms=a-b-c")
    assert yaml.safe_load(vault.file.read_text()) == vault.load()


def test_set_validates_and_never_echoes(tmp_path, plain):
    vault = Vault(tmp_path)
    vault.set("orchestrator-token", "  0c1d-secret  ")
    assert vault.get("orchestrator-token") == "0c1d-secret"
    with pytest.raises(VaultError, match="full form"):
        vault.set("proxmox-token", "only-the-secret")
    with pytest.raises(VaultError, match="whitespace"):
        vault.set("topology-token", "a b")
    with pytest.raises(VaultError, match="unknown secret"):
        vault.set("vault_postgres_admin_password", "x")
    assert not any("0c1d-secret" in str(cell) for row in vault.status() for cell in row)


@needs_ssh_keygen
def test_importing_an_ssh_key(tmp_path, plain):
    key = tmp_path / "id"
    subprocess.run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C", "node", "-f", str(key)], check=True)
    vault = Vault(tmp_path)
    vault.set("ssh-key", key.read_text())
    values = vault.load()
    assert values[SSH_PUBLIC_KEY].split()[:2] == key.with_suffix(".pub").read_text().split()[:2]
    with pytest.raises(VaultError, match="private key"):
        vault.set("ssh-key", "not a key")


@needs_ssh_keygen
def test_encrypted_at_rest_with_ansible_vault(tmp_path):
    if not shutil.which("ansible-vault"):
        pytest.skip("not installed: ansible-vault")
    vault = Vault(tmp_path)
    vault.ensure()
    vault.set("proxmox-token", "root@pam!worms=enc-secret")
    text = vault.file.read_text()
    assert text.startswith("$ANSIBLE_VAULT") and "enc-secret" not in text
    assert vault.get("proxmox-token") == "root@pam!worms=enc-secret"
    assert sorted(p.name for p in vault.file.parent.iterdir()) == ["vault.yml"]  # no plaintext left behind


def cli(root, *args, input=None):
    env = {**os.environ, "WORMS_REPO_ROOT": str(root), "HOME": str(root / "home"), "NO_COLOR": "1"}
    env.pop("WORMS_SSH", None)
    return subprocess.run([sys.executable, str(MANAGE), *args], env=env, input=input, capture_output=True, text=True)


@needs_ssh_keygen
def test_secrets_command(tmp_path):
    (tmp_path / "ansible").mkdir()
    shutil.copy(REPO / "ansible" / "ansible.cfg", tmp_path / "ansible")
    proc = cli(tmp_path, "secrets", "set", "proxmox-token", input="root@pam!worms=from-stdin\n")
    assert proc.returncode == 0, proc.stderr
    listing = cli(tmp_path, "secrets")
    assert listing.returncode == 0, listing.stderr
    assert "proxmox-token" in listing.stdout and "from-stdin" not in listing.stdout + listing.stderr
    assert "MISSING" in listing.stdout  # orchestrator-token
    assert Vault(tmp_path).get("proxmox-token") == "root@pam!worms=from-stdin"
    bad = cli(tmp_path, "secrets", "set", "proxmox-token", input="nope\n")
    assert bad.returncode != 0 and "full form" in bad.stderr


# --- the secrets step of the pipeline (before/after guard for refactorings) --


ENTERED = {"vault_proxmox_api_token_value", "vault_proxmox_readonly_api_token_value", "vault_tofu_proxmox_api_token"}


def test_build_secrets_provides_every_vault_variable(tmp_path):
    """`worms build secrets` in a fresh checkout yields every vault_* variable
    the Ansible side refers to (the Proxmox tokens are entered by the operator,
    so they may be absent or empty), and a second run changes nothing."""
    import re

    root = tmp_path / "checkout"
    for part in ("src", "scripts", "ansible"):
        shutil.copytree(REPO / part, root / part, ignore=shutil.ignore_patterns(
            "vault.yml", ".vault_pass", "inventory.generated.yml", "pki", "__pycache__", ".venv*"))  # fmt: skip
    bin_dir = tmp_path / "bin"  # no ansible-vault: the vault stays readable
    bin_dir.mkdir()
    (bin_dir / "python3").symlink_to(sys.executable)
    (bin_dir / "sh").symlink_to(shutil.which("sh"))
    if shutil.which("ssh-keygen"):  # the WORMS SSH key is generated with it
        (bin_dir / "ssh-keygen").symlink_to(shutil.which("ssh-keygen"))
    env = {"PATH": str(bin_dir), "HOME": str(tmp_path / "home"), "WORMS_REPO_ROOT": str(root), "NO_COLOR": "1"}

    def build_secrets():
        proc = subprocess.run([sys.executable, str(root / "src" / "manage.py"), "build", "secrets"], env=env,
                              capture_output=True, text=True)  # fmt: skip
        assert proc.returncode == 0, proc.stdout + proc.stderr
        return (root / "ansible" / "group_vars" / "vault.yml").read_text()

    first = build_secrets()
    vault = yaml.safe_load(first)
    referenced = set()
    for path in (root / "ansible").rglob("*"):
        if path.suffix in (".yml", ".j2") and path.name != "vault.yml":
            # Variables used in Jinja expressions ({{ vault_x }}), not file names.
            for expression in re.findall(r"\{\{(.*?)\}\}", path.read_text(), re.S):
                referenced |= set(re.findall(r"\bvault_[a-z_]+", expression))
    assert referenced, "no vault_* variable found (the scan is broken)"
    for key in sorted(referenced - ENTERED):
        assert len(str(vault.get(key) or "")) >= 16, f"{key} is not generated"
    assert build_secrets() == first  # never rotated
