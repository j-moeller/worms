    def _create_teams(
        self,
        *,
        competition,
        users,
        n_teams,
        state,
        seed,
        rng,
    ):
        adjectives = [
            "Binary",
            "Null",
            "Kernel",
            "Packet",
            "Root",
            "Shadow",
            "Cipher",
            "Buffer",
            "Stack",
            "Daemon",
            "Socket",
            "Hex",
            "Vector",
            "Signal",
            "Bit",
            "Opcode",
        ]

        nouns = [
            "Foxes",
            "Ravens",
            "Wolves",
            "Owls",
            "Lynx",
            "Badgers",
            "Dragons",
            "Wasps",
            "Sharks",
            "Vipers",
            "Hawks",
            "Falcons",
        ]

        combinations = [(adjective, noun) for adjective in adjectives for noun in nouns]

        rng.shuffle(combinations)

        teams = []

        for index in range(n_teams):
            dev_competition = Competition.objects.create(
                name="Cyber Defense Competition (DEV)",
                created_at=self._competition_created_at(),
                registration_starts_at=None,
                registration_ends_at=None,
                is_dev_competition=True,
            )
            dev_round = Round.objects.create(
                seed=0,
                round_start=None,
                round_end=None,
                name="Round Dev",
                competition=dev_competition,
                created_at=self._competition_created_at(),
            )

            adjective, noun = combinations[index % len(combinations)]

            cycle = index // len(combinations)

            if cycle == 0:
                team_name = f"{adjective} {noun}"
            else:
                team_name = f"{adjective} {noun} {cycle + 1}"

            team = Team.objects.create(
                uuid=self._uuid(
                    seed,
                    "team",
                    index,
                ),
                name=team_name,
                competition=competition,
                development_competition=dev_competition,
                max_members=2,
            )

            # No random timestamp or random temporal state is attached
            # to the team.
            teams.append(team)

        if state in {
            "registration ended",
            "round",
            "finished",
        }:
            self._assign_users_to_teams(
                users=users,
                teams=teams,
                rng=rng,
            )

        return teams

    def _assign_users_to_teams(
        self,
        *,
        users,
        teams,
        rng,
    ):
        shuffled_users = list(users)
        rng.shuffle(shuffled_users)

        # Guarantee every team gets one member.
        for index, team in enumerate(teams):
            TeamMembership.objects.create(
                user=shuffled_users[index],
                team=team,
            )

        remaining_users = shuffled_users[len(teams) :]

        rng.shuffle(remaining_users)

        for user in remaining_users:
            eligible = [
                team
                for team in teams
                if team.team_memberships.count() < team.max_members
            ]

            if not eligible:
                raise CommandError("Could not assign all users to teams.")

            team = rng.choice(eligible)

            TeamMembership.objects.create(
                user=user,
                team=team,
            )

