#!/usr/bin/env python3
"""Generate management secrets into the Ansible vault, idempotently.

Internal service credentials — every PostgreSQL role password, the Django
SECRET_KEYs and the internal CA passphrase — are generated here so you never
have to type, know or track them. They are written ONCE to
ansible/group_vars/vault.yml, encrypted with ansible-vault using a
locally-generated key file (ansible/.vault_pass). On every later run, if the
vault already exists, this does NOTHING: the stored passwords stay stable so
they keep matching what is already configured on the database and the VMs, and
`make` stays fully idempotent.

The ONE secret this cannot invent is the Proxmox API token — it must equal the
token Proxmox issued you. Provide it via the PROXMOX_API_TOKEN environment
variable before the first run; otherwise a placeholder is written and a notice
printed, and you can set it later with:

    cd ansible
    ansible-vault edit --vault-password-file .vault_pass group_vars/vault.yml

Both ansible/.vault_pass and ansible/group_vars/vault.yml are git-ignored.
Standard library only.
"""

from __future__ import annotations

import argparse
import os
import secrets
import shutil
import subprocess
import sys
from pathlib import Path

# Internal secrets we own and generate. name -> number of random bytes.
GENERATED_PASSWORDS = {
    "vault_postgres_admin_password": 24,
    "vault_postgres_migrator_password": 24,
    "vault_django_dashboard_password": 24,
    "vault_django_orchestrator_password": 24,
    "vault_dbuser_logging_password": 24,
    "vault_dbuser_network_monitor_password": 24,
    "vault_dbuser_scoring_password": 24,
    "vault_pki_ca_passphrase": 24,
}
GENERATED_SECRET_KEYS = {
    "vault_dashboard_secret_key": 64,  # Django SECRET_KEY
    "vault_orchestrator_secret_key": 64,
}
# External secret we cannot invent (must match what Proxmox issued).
PROXMOX_TOKEN_KEY = "vault_proxmox_api_token_value"
PROXMOX_TOKEN_ENV = "PROXMOX_API_TOKEN"
PROXMOX_PLACEHOLDER = "REPLACE_WITH_PROXMOX_API_TOKEN"


def token(nbytes: int) -> str:
    # URL-safe: only [A-Za-z0-9_-], safe unquoted in env files and PostgreSQL.
    return secrets.token_urlsafe(nbytes)


def render_vault(proxmox_token: str) -> str:
    lines = [
        "# GENERATED by scripts/generate_secrets.py. Do not edit by hand except",
        "# to set the Proxmox API token. Regenerate only by deleting this file",
        "# (which rotates every secret and requires re-provisioning the DB/VMs).",
        "",
        "# --- PostgreSQL role passwords (internal, auto-generated) ---",
    ]
    for key in GENERATED_PASSWORDS:
        if key == "vault_pki_ca_passphrase":
            continue
        lines.append(f'{key}: "{token(GENERATED_PASSWORDS[key])}"')
    lines += [
        "",
        "# --- Internal CA passphrase (auto-generated) ---",
        f'vault_pki_ca_passphrase: "{token(GENERATED_PASSWORDS["vault_pki_ca_passphrase"])}"',
        "",
        "# --- Django SECRET_KEYs (auto-generated) ---",
    ]
    for key in GENERATED_SECRET_KEYS:
        lines.append(f'{key}: "{token(GENERATED_SECRET_KEYS[key])}"')
    lines += [
        "",
        "# --- Proxmox API token (EXTERNAL: must match the token Proxmox issued) ---",
        f'{PROXMOX_TOKEN_KEY}: "{proxmox_token}"',
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    script_dir = Path(__file__).resolve().parent
    repo_root = script_dir.parent

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=repo_root)
    parser.add_argument("--vault-file", type=Path, default=None)
    parser.add_argument("--vault-pass-file", type=Path, default=None)
    parser.add_argument("--force", action="store_true",
                        help="Regenerate even if the vault exists (ROTATES all "
                             "secrets; you must then re-provision the DB and VMs).")
    args = parser.parse_args()

    root = args.repo_root.resolve()
    vault_file = args.vault_file or (root / "ansible" / "group_vars" / "vault.yml")
    vault_pass_file = args.vault_pass_file or (root / "ansible" / ".vault_pass")

    # Idempotent: if the vault is already there, leave it (and its passwords) alone.
    if vault_file.exists() and not args.force:
        print(f"secrets: {vault_file} already present — leaving it unchanged.")
        return

    # Vault password file (so Ansible never prompts). Generate once.
    if not vault_pass_file.exists():
        vault_pass_file.parent.mkdir(parents=True, exist_ok=True)
        vault_pass_file.write_text(token(32) + "\n")
        vault_pass_file.chmod(0o600)
        print(f"secrets: generated vault key file {vault_pass_file}")

    # The one external secret.
    proxmox_token = os.environ.get(PROXMOX_TOKEN_ENV, "").strip() or PROXMOX_PLACEHOLDER

    vault_file.parent.mkdir(parents=True, exist_ok=True)
    vault_file.write_text(render_vault(proxmox_token))
    vault_file.chmod(0o600)

    # Encrypt at rest if ansible-vault is available.
    if shutil.which("ansible-vault"):
        subprocess.run(
            ["ansible-vault", "encrypt",
             "--vault-password-file", str(vault_pass_file), str(vault_file)],
            check=True,
        )
        print(f"secrets: wrote and encrypted {vault_file}")
    else:
        print(f"secrets: wrote {vault_file} (ansible-vault not found; left PLAINTEXT — "
              "it is git-ignored, but install Ansible to encrypt it)")

    n = len(GENERATED_PASSWORDS) + len(GENERATED_SECRET_KEYS)
    print(f"secrets: generated {n} internal credentials (never printed).")

    if proxmox_token == PROXMOX_PLACEHOLDER:
        print("=" * 64, file=sys.stderr)
        print("NOTICE: Proxmox API token not set.", file=sys.stderr)
        print(f"  Set {PROXMOX_TOKEN_ENV} before the first run, or edit it in:",
              file=sys.stderr)
        print("    cd ansible && ansible-vault edit "
              "--vault-password-file .vault_pass group_vars/vault.yml",
              file=sys.stderr)
        print("  The orchestrator cannot reach Proxmox until this is set.",
              file=sys.stderr)
        print("=" * 64, file=sys.stderr)


if __name__ == "__main__":
    main()
